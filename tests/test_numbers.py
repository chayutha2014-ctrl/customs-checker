"""ชุดทดสอบการแยกวิเคราะห์ตัวเลข — ทุกกรณีมาจากเอกสารจริง"""
import pytest
from customs_checker.numbers import parse_number


@pytest.mark.parametrize("raw,expect", [
    # ตัวเลขปกติ
    ("100,420.15",  100420.15),
    ("45,150.00",   45150.00),
    ("8.30",        8.30),
    ("156.87",      156.87),
    ("0.86",        0.86),
    ("1,000",       1000.0),
    ("52500",       52500.0),
    ("3.5",         3.5),
    ("¥35,700.00",  35700.00),
    ("$3,090.00",   3090.00),
    # VORETO — OCR อ่านจุลภาคเป็นจุด
    ("26.947.32",   26947.32),
    ("$26.947.32",  26947.32),
    # HUANYU — มีเลขลำดับเขียนมือกำกับข้างจำนวนเงิน
    ("1,056.00 22", 1056.00),
    ("258.00 1",    258.00),
    ("10,797.20",   10797.20),
    # ปริมาณที่มีหน่วยต่อท้าย
    ("150.00 MTR",  150.00),
    ("500 PCS",     500.0),
])
def test_parse(raw, expect):
    assert parse_number(raw) == pytest.approx(expect)


@pytest.mark.parametrize("code", [
    "1-2-051-000",      # รหัสสินค้า HUANYU
    "B248-SSI3",        # รหัส ECO
    "F930001",          # รหัส FUJIAN
    "5232QAXXX12616W",
    "886-2-2369",       # เบอร์โทร
    "DM-SS20260824",    # เลขที่ Invoice
    "4183006811",       # PO — ตัวเลขล้วน ยังผ่านได้ ไม่มีทางแยก
])
def test_รหัสไม่ใช่ตัวเลขที่ใช้คำนวณ(code):
    v = parse_number(code)
    assert v is None or code == "4183006811"


@pytest.mark.parametrize("junk", ["", "ABC", ".", ",", "-", "N/A", "TOTAL"])
def test_ไม่ใช่ตัวเลขคืนค่าว่าง(junk):
    assert parse_number(junk) is None


def test_ห้ามบดสองจำนวนเป็นจำนวนเดียว():
    """เคสที่ทำให้ระบบพังทั้งใบ — ต้องไม่ได้ 10,560,022"""
    assert parse_number("1,056.00 22") == 1056.00


@pytest.mark.parametrize("raw,expect", [
    # VORETO ใช้ราคาทศนิยม 4 ตำแหน่ง — เคสที่ทำให้ระบบพังทั้งใบ
    ("27.1800",     27.18),
    ("$27.1800",    27.18),
    ("1.7400",      1.74),
    ("15.6800",     15.68),
    ("45.1200",     45.12),
    ("118.2300",    118.23),
    # รูปแบบใบขนไทย ทศนิยม 3 ตำแหน่ง
    ("500.000",     500.0),
    ("365.000",     365.0),
    # หลักพันแบบยุโรป
    ("1.234.567",   1234567.0),
])
def test_ทศนิยมหลายตำแหน่งต้องไม่กลายเป็นหลักพัน(raw, expect):
    assert parse_number(raw) == pytest.approx(expect)
